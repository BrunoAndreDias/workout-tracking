import { chromium } from 'playwright'
import { longDate, openFresh, readStored, reloadApp } from './_driver.mjs'
const S = process.env.SHOTS ?? 'e2e/shots'
const URL = process.env.APP_URL ?? 'http://localhost:5180/'
const assert = (ok, msg) => { if (!ok) throw new Error('FAIL: ' + msg); console.log('ok:', msg) }
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('dialog', (d) => d.accept())
await openFresh(page, URL + '#alimentacao')

const pad = (n) => String(n).padStart(2, '0')
const iso = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
const daysAgo = (n) => { const d = new Date(); d.setHours(12); d.setDate(d.getDate() - n); return d }
const view = (name) => page.getByRole('navigation', { name: 'Secções' }).getByRole('link', { name })
const tab = (name) => page.getByRole('navigation', { name: 'Treino' }).getByRole('button', { name })
const region = (name) => page.getByRole('region', { name, exact: true })
const noScroll = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
const values = (lift, field) => lift.getByLabel(new RegExp(`^${field} da série`)).evaluateAll((els) => els.map((e) => e.value))
const addExercise = async (scope, name) => {
  await scope.getByLabel('Exercício a adicionar').fill(name)
  await scope.getByLabel('Exercício a adicionar').press('Enter')
}

await view('Treino').click()
assert(page.url().endsWith('#treino'), 'Treino view is in the URL hash')
await tab('Plano de treino').click()
await page.getByRole('button', { name: 'Criar plano de treino' }).click()
await page.getByRole('button', { name: 'Adicionar dia' }).click()
await page.getByRole('button', { name: /^Nome do dia de treino: Dia 1/ }).click()
await page.getByLabel('Nome do dia de treino').fill('Peito')
await page.getByLabel('Nome do dia de treino').press('Enter')
const peitoDay = region('Peito')
await addExercise(peitoDay, 'Supino')
await addExercise(peitoDay, 'Elevações')
await addExercise(peitoDay, 'supino ')
assert((await peitoDay.locator('.planned-name').allTextContents()).join('|') === 'Supino|Elevações', 'typing an existing name ignoring case adds nothing new')
await peitoDay.getByLabel('Séries de Supino').fill('4')
await peitoDay.getByLabel('Repetições de Supino').fill('6-8')
await peitoDay.getByLabel('Repetições de Supino').blur()
assert(await peitoDay.getByLabel('Repetições de Supino').inputValue() === '6–8', 'rep range reads 6–8 after editing')
await page.screenshot({ path: `${S}/workout-plan-desktop.png`, fullPage: true })

await tab('Registo').click()
await page.getByRole('button', { name: 'Dia anterior' }).click()
const yesterday = iso(daysAgo(1))
assert(page.url().endsWith(`#treino/${yesterday}`), 'the logged date is in the URL hash')
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(1)) }).waitFor()
assert((await page.locator('.date-stepper h2').textContent()) === longDate.format(daysAgo(1)), `the header names yesterday (got ${await page.locator('.date-stepper h2').textContent()})`)
await page.getByRole('button', { name: 'Peito', exact: true }).click()
const session = region('Peito')
const supino = session.getByRole('group', { name: 'Supino' })
const elevacoes = session.getByRole('group', { name: 'Elevações' })
assert(JSON.stringify(await values(supino, 'Repetições')) === '["","","",""]', 'a first session has 4 empty Supino sets, as planned')
assert(await supino.locator('.lift-target').textContent() === 'Plano 4 × 6–8', 'the planned target shows next to the exercise')
await supino.getByLabel('Repetições da série 1 de Supino').fill('8')
await supino.getByLabel('Kg da série 1 de Supino').fill('60')
await supino.getByLabel('Repetições da série 2 de Supino').fill('7')
await supino.getByLabel('Kg da série 2 de Supino').fill('62,5')
await supino.getByRole('button', { name: 'Remover série 4 de Supino' }).click()
await supino.getByRole('button', { name: 'Remover série 3 de Supino' }).click()
for (const [i, reps] of ['10', '9', '8'].entries()) await elevacoes.getByLabel(`Repetições da série ${i + 1} de Elevações`).fill(reps)
await elevacoes.getByRole('button', { name: 'Adicionar série a Elevações' }).click()
assert(JSON.stringify(await values(elevacoes, 'Repetições')) === '["10","9","8","8"]', 'a new set copies the one before it')
await elevacoes.getByRole('button', { name: 'Remover série 4 de Elevações' }).click()
await session.getByLabel('Notas do treino').fill('Ombro bem')
assert(await region('Treinos anteriores').count() === 0, 'with no session in the three days before, there is no Treinos anteriores card')
const endFeel = session.getByRole('group', { name: 'No fim do treino' })
await endFeel.getByRole('button', { name: 'No fim do treino: Bem' }).click()
const supinoNoteToggle = supino.getByRole('button', { name: 'Nota de Supino' })
assert(await supinoNoteToggle.getAttribute('aria-expanded') === 'false', 'an exercise note starts closed')
await supinoNoteToggle.click()
const supinoNote = supino.getByRole('textbox', { name: 'Nota de Supino' })
assert(await supinoNote.getAttribute('placeholder') === 'Dores, desconforto, como correu', 'the exercise note asks about pain and discomfort')
assert(await supino.getByRole('button', { name: 'Ditar nota' }).count() === 1, 'an exercise note has a mic button')
await supinoNote.fill('Ombro esq. a picar na 2.ª série')
const liftTimes = await supino.locator('.note-times').textContent()
assert(/^Escrito a \d+ [a-z]{3}, \d\d:\d\d$/.test(liftTimes), `the exercise note shows when it was written (got ${liftTimes})`)
await supinoNoteToggle.click()
assert(await supinoNoteToggle.locator('.notes-dot').count() === 1, 'a closed exercise note with text shows the dot')
assert(await elevacoes.getByRole('button', { name: 'Nota de Elevações' }).locator('.notes-dot').count() === 0, 'an empty one does not')

await reloadApp(page)
assert(JSON.stringify(await values(supino, 'Repetições')) === '["8","7"]' && JSON.stringify(await values(supino, 'Kg')) === '["60","62,5"]', 'Supino sets persisted across reload')
assert(JSON.stringify(await values(elevacoes, 'Kg')) === '["","",""]', 'Elevações stays bodyweight, with no kg')
assert(await session.getByLabel('Notas do treino').inputValue() === 'Ombro bem', 'notes persisted')
assert(await endFeel.getByRole('button', { pressed: true }).textContent() === 'Bem', 'the end feel persisted across reload')
const sessionTimes = await session.locator('.session-foot .note-times').textContent()
assert(/^Escrito a \d+ [a-z]{3}, \d\d:\d\d$/.test(sessionTimes), `the session note shows when it was written (got ${sessionTimes})`)
assert(await supinoNote.inputValue() === 'Ombro esq. a picar na 2.ª série', 'the exercise note persisted and opens by itself')
assert(await supino.locator('.note-times').textContent() === liftTimes, 'and so did when it was written')
const stored = await readStored(page)
assert(stored['workout-sessions'].version === 2 && stored['workout-sessions'].sessions.length === 1, 'one session stored under its own key')
assert(stored['workout-sessions'].sessions[0].feel === 4 && !('after' in stored['workout-sessions'].sessions[0]), 'the end feel is stored as 4, and no After-effects key yet')
const storedNote = stored['workout-sessions'].sessions[0].note
assert(storedNote.text === 'Ombro bem' && /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d$/.test(storedNote.createdAt), `the session note is stored with when it was written (got ${JSON.stringify(storedNote)})`)
assert(JSON.stringify(stored['workout-sessions'].sessions[0].exercises[0].sets) === '[{"reps":8,"kg":60},{"reps":7,"kg":62.5}]', 'stored sets are numbers, kg in decimals')
assert(stored['workout-sessions'].sessions[0].exercises[0].note.text === 'Ombro esq. a picar na 2.ª série' && !('note' in stored['workout-sessions'].sessions[0].exercises[1]), 'the note is stored on its exercise only')
assert(stored.exercises.exercises.map((e) => e.name).join('|') === 'Supino|Elevações', 'two exercises stored')

await view('Diário').click()
await page.locator('.calendar').waitFor()
await page.getByRole('button', { name: new RegExp(`^${longDate.format(daysAgo(1))}(,|$)`) }).click()
const line = page.locator('.workout-line')
assert((await line.textContent()) === 'TreinoPeito2 exercícios, 5 séries', `Diário shows the session line (got ${await line.textContent()})`)
await page.screenshot({ path: `${S}/workout-diario-line.png`, fullPage: true })
await line.click()
assert(page.url().endsWith(`#treino/${yesterday}`), 'the Diário line links to the session date')
await region('Peito').waitFor()

await page.getByRole('button', { name: 'Dia seguinte' }).click()
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(0)) }).waitFor()
assert(await page.getByRole('button', { name: 'Dia seguinte' }).isDisabled(), 'today is the last day that can be logged')
const recent = region('Treinos anteriores').getByRole('group', { name: 'Peito, ontem' })
assert(await recent.locator('.recent-meta').textContent() === 'ontem · no fim: Bem', `the day after, Treinos anteriores lists yesterday's session with its end feel (got ${await recent.locator('.recent-meta').textContent()})`)
await recent.getByRole('textbox', { name: 'Como está hoje' }).fill('Peito dorido')
await recent.getByRole('button', { name: 'Nota de Supino' }).click()
await recent.getByRole('textbox', { name: 'Nota de Supino' }).fill('Ombro esq. dói ao levantar o braço')
await reloadApp(page)
assert(await recent.getByRole('textbox', { name: 'Como está hoje' }).inputValue() === 'Peito dorido', 'the session note of the day after persisted across reload')
assert(await recent.getByRole('textbox', { name: 'Nota de Supino' }).inputValue() === 'Ombro esq. dói ao levantar o braço', 'and the Supino one, open by itself')
const after = (await readStored(page))['workout-sessions'].sessions[0].after.map((a) => [a.date, a.exerciseId === null ? null : 'supino', a.note.text])
assert(JSON.stringify(after) === JSON.stringify([[iso(daysAgo(0)), null, 'Peito dorido'], [iso(daysAgo(0)), 'supino', 'Ombro esq. dói ao levantar o braço']]), `two After-effects stored on yesterday's session, dated today (got ${JSON.stringify(after)})`)
await page.getByRole('button', { name: 'Dia anterior' }).click()
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(1)) }).waitFor()
const afterList = region('Peito').getByRole('group', { name: 'Depois do treino' })
const items = await afterList.locator('.after-item').evaluateAll((lis) => lis.map((li) => [...li.children].slice(0, 2).map((c) => c.textContent).join(' / ')))
assert(JSON.stringify(items) === JSON.stringify(['Dia seguinteTreino / Peito dorido', 'Dia seguinteSupino / Ombro esq. dói ao levantar o braço']), `the original session card shows them read only (got ${JSON.stringify(items)})`)
await page.screenshot({ path: `${S}/workout-after-effects.png`, fullPage: true })
await page.getByRole('button', { name: 'Dia seguinte' }).click()
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(0)) }).waitFor()
await page.getByRole('button', { name: 'Peito', exact: true }).click()
assert(JSON.stringify(await values(supino, 'Repetições')) === '["8","7","7","7"]', 'a second session pre-fills Supino reps from the last time, repeating the last set')
assert(JSON.stringify(await values(supino, 'Kg')) === '["60","62,5","62,5","62,5"]', 'and its kg')
assert(JSON.stringify(await values(elevacoes, 'Repetições')) === '["10","9","8"]', 'Elevações pre-fills its three sets')
await addExercise(session, 'Prancha')
assert(JSON.stringify(await values(session.getByRole('group', { name: 'Prancha' }), 'Repetições')) === '[""]', 'a new exercise starts with one empty set')
await page.screenshot({ path: `${S}/workout-session-desktop.png`, fullPage: true })

await page.setViewportSize({ width: 390, height: 844 })
assert(await noScroll(), 'Treino Registo has no horizontal scroll at 390 px')
await page.screenshot({ path: `${S}/workout-session-mobile.png`, fullPage: true })
await tab('Plano de treino').click()
await region('Peito').waitFor()
assert(await noScroll(), 'Plano de treino has no horizontal scroll at 390 px')
await page.screenshot({ path: `${S}/workout-plan-mobile.png`, fullPage: true })
await view('Diário').click()
await page.locator('.workout-line').waitFor()
assert(await noScroll(), 'Diário with a session line has no horizontal scroll at 390 px')
await page.screenshot({ path: `${S}/workout-diario-mobile.png`, fullPage: true })

assert(errors.length === 0, 'no console errors: ' + errors.join(' / '))
await browser.close()
