import { chromium } from 'playwright'
import { addExercise, createWorkoutPlan, daysAgo, longDate, openFresh, readStored, reloadApp, swapExercise, toIsoDate, workoutDay } from './_driver.mjs'
const S = process.env.SHOTS ?? 'e2e/shots'
const URL = process.env.APP_URL ?? 'http://localhost:5180/'
const assert = (ok, msg) => { if (!ok) throw new Error('FAIL: ' + msg); console.log('ok:', msg) }
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('dialog', (d) => d.accept())
await openFresh(page, URL)

const tab = (name) => page.getByRole('navigation', { name: 'Treino' }).getByRole('button', { name })
const region = (name) => page.getByRole('region', { name, exact: true })
const noScroll = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
const values = (lift, field) => lift.getByLabel(new RegExp(`^${field} da série`)).evaluateAll((els) => els.map((e) => e.value))
const ticks = (lift) => lift.locator('.set-tick').evaluateAll((els) => els.map((e) => e.getAttribute('aria-pressed')))
const BENCH = 'Flat Dumbbell Bench Press'
const OHP = 'Standing Overhead Barbell Press'

await tab('Plano de treino').click()
assert((await page.locator('.split-tile').allTextContents()).join('|') === '3 diasPush · Pull · Full body|4 diasUpper A · Lower A · Upper B · Lower B', 'a new plan offers the 3-day and the 4-day split')
await createWorkoutPlan(page, { name: 'Força', days: 3 })
assert((await page.getByRole('navigation', { name: 'Dias de Bloco A' }).getByRole('button').allTextContents()).join('|') === 'Push|Pull|Full body', 'the plan’s days are Push, Pull and Full body tabs')
assert(!(await page.getByRole('checkbox', { name: /^Semana leve/ }).isChecked()), 'Bloco A is not a light block')
const push = await workoutDay(page, 'Push')
assert((await push.locator('.planned-name').allTextContents()).join('|') === 'Flat Barbell Bench Press|Standing Overhead Barbell Press|Dumbbell Lateral Raises|Cable Press-Downs|Cable Crunches', 'Push comes filled from the template')
assert((await push.locator('.role-label').allTextContents()).join('|') === 'Principal|Secundário|Isolamento|Isolamento|Abs', 'each row shows its role')
assert(await push.getByLabel('Repetições de Flat Barbell Bench Press').inputValue() === '6–8', 'a main lift aims at 6–8 reps')
const pushMuscles = push.getByRole('complementary', { name: 'Músculos de Push' })
const daySets = () => pushMuscles.locator('.day-muscle').evaluateAll((els) => els.map((e) => [...e.querySelectorAll('.muscle-name, .muscle-sets')].map((s) => s.textContent).join(' ')).join(' | '))
assert(await daySets() === 'Peito 3 séries | Ombros 6 séries | Tríceps 3 séries | Abdominais 3 séries', 'beside its list, Push shows the sets of each muscle group it trains')
await push.screenshot({ path: `${S}/workout-day-muscles.png` })
await page.setViewportSize({ width: 375, height: 812 })
assert(await noScroll(), 'Push with its muscle sets has no horizontal scroll at 375 px')
await push.screenshot({ path: `${S}/workout-day-muscles-mobile.png` })
await page.setViewportSize({ width: 1280, height: 900 })
const weekly = region('Músculos por semana')
const weekSets = (name) => weekly.locator('.volume-row', { has: page.locator('.muscle-name', { hasText: new RegExp(`^${name}$`) }) }).locator('.volume-sets').textContent()
assert(await weekSets('Peito') === '6 séries', 'Músculos por semana gives Peito 6 sets a week (e2e/muscle-volume.mjs drives the rest)')
await push.getByLabel('Séries de Flat Barbell Bench Press').fill('5')
assert(await weekSets('Peito') === '8 séries', 'raising the bench press to 5 sets makes Peito 8 sets a week')
assert(await daySets() === 'Peito 5 séries | Ombros 6 séries | Tríceps 3 séries | Abdominais 3 séries', 'and Peito 5 sets on Push')
await push.getByLabel('Séries de Flat Barbell Bench Press').fill('3')
assert(await weekSets('Peito') === '6 séries', 'and back to 3 sets, 6')

await push.getByRole('button', { name: 'Trocar Flat Barbell Bench Press' }).click()
const picker = page.getByRole('dialog')
assert((await picker.getByRole('region', { name: 'Mesmo movimento' }).locator('.result-name').first().textContent()) === BENCH, 'swapping lists the same movement first')
await picker.getByRole('button', { name: 'Fechar', exact: true }).click()
await swapExercise(push, 'Flat Barbell Bench Press', BENCH)
assert((await push.locator('.planned-name').first().textContent()) === BENCH && (await push.locator('.role-label').first().textContent()) === 'Principal', 'the swap keeps the place and the role')
await push.getByRole('button', { name: `Remover ${OHP} de Push` }).click()
await addExercise(push, OHP)
assert((await push.locator('.role-label').last().textContent()) === 'Secundário', 'a catalog compound added by hand starts as secondary')
await addExercise(push, 'Supino')
assert(await region('Músculos por semana').getByText('Sem grupo muscular: Supino (3 séries)').count() === 1, 'an Exercise of the user’s own is counted apart, with no muscle group')
assert((await push.locator('.role-label').last().textContent()) === 'Isolamento', 'a name of the user’s own starts as isolation')
await push.getByRole('button', { name: 'Exercício', exact: true }).click()
await picker.getByLabel('Pesquisar exercício').fill('supino ')
assert(await picker.getByRole('region', { name: 'Os teus' }).getByRole('button', { name: /Supino/ }).isDisabled(), 'an Exercise already in the day cannot be picked again, ignoring case')
assert(await picker.getByRole('button', { name: /Criar/ }).count() === 0, 'nor created again')
await picker.getByRole('button', { name: 'Fechar', exact: true }).click()
await push.getByLabel('Função de Supino').selectOption('main')
await push.getByLabel('Séries de Supino').fill('4')
await push.getByLabel('Repetições de Supino').fill('6-8')
await push.getByLabel('Repetições de Supino').blur()
assert(await push.getByLabel('Repetições de Supino').inputValue() === '6–8', 'rep range reads 6–8 after editing')
for (const name of ['Dumbbell Lateral Raises', 'Cable Press-Downs', 'Cable Crunches', BENCH]) await push.getByRole('button', { name: `Remover ${name} de Push` }).click()
assert((await push.locator('.planned-name').allTextContents()).join('|') === `${OHP}|Supino`, 'Push keeps the two exercises left')
await page.screenshot({ path: `${S}/workout-plan-desktop.png`, fullPage: true })

await tab('Registo').click()
await page.getByRole('button', { name: 'Dia anterior' }).click()
const yesterday = toIsoDate(daysAgo(1))
assert(page.url().endsWith(`#treino/${yesterday}`), 'the logged date is in the URL hash')
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(1)) }).waitFor()
const starts = () => page.locator('.day-start button').allTextContents()
assert((await starts()).join('|') === 'Começar Push|Pull|Full body|Treino livre', `with no session yet, Registo starts with the first day (got ${(await starts()).join('|')})`)
await page.getByRole('button', { name: 'Começar Push' }).click()
const session = region('Push')
const supino = session.getByRole('group', { name: 'Supino' })
const ohp = session.getByRole('group', { name: OHP })
assert(JSON.stringify(await values(supino, 'Repetições')) === '["","","",""]', 'a first session has 4 empty Supino sets, as planned')
assert(await supino.locator('.lift-target').textContent() === 'Plano 4 × 6–8. ', 'the planned target shows under the exercise')
assert(await supino.getByRole('button', { name: 'Série 1 de Supino feita' }).isDisabled(), 'a set with no reps cannot be ticked')
await supino.getByLabel('Kg da série 1 de Supino').fill('60')
await supino.getByLabel('Repetições da série 1 de Supino').fill('8')
await supino.getByLabel('Kg da série 2 de Supino').fill('61,25')
await supino.getByLabel('Repetições da série 2 de Supino').fill('7')
await supino.getByLabel('Kg da série 3 de Supino').fill('61,257')
await supino.getByLabel('Kg da série 3 de Supino').blur()
assert(JSON.stringify(await values(supino, 'Kg')) === '["60","61,25","61,26",""]', `kg shows up to two decimals, and more typed are rounded (got ${JSON.stringify(await values(supino, 'Kg'))})`)
assert(JSON.stringify(await ticks(supino)) === '["false","false","false","false"]', 'typing kg and reps never marks a set done')
await supino.getByRole('button', { name: 'Série 1 de Supino feita' }).click()
await supino.getByRole('button', { name: 'Série 2 de Supino feita' }).click()
await supino.getByRole('button', { name: 'Série 2 de Supino feita' }).click()
assert(JSON.stringify(await ticks(supino)) === '["true","false","false","false"]', '✓ again un-marks a set')
await supino.getByRole('button', { name: 'Série 2 de Supino feita' }).click()
await supino.getByRole('button', { name: 'Remover série 4 de Supino' }).click()
await supino.getByRole('button', { name: 'Remover série 3 de Supino' }).click()
assert(await supino.locator('.lift-check').textContent() === '✓ 2 séries', 'an exercise with every set done collapses to one line')
assert(await ohp.getByRole('group', { name: `RIR da série 1 de ${OHP}` }).count() === 1, 'the next exercise with a set to do shows the RIR chips')
for (const [i, reps] of ['10', '9', '8'].entries()) await ohp.getByLabel(`Repetições da série ${i + 1} de ${OHP}`).fill(reps)
await ohp.getByRole('button', { name: `RIR 2 na série 1 de ${OHP}` }).click()
assert(JSON.stringify(await ohp.locator('.set-rir').allTextContents()) === '["RIR 2","RIR 2",""]', 'picking a RIR copies it to the next pending set with none')
await ohp.getByRole('button', { name: `Adicionar série a ${OHP}` }).click()
assert(JSON.stringify(await values(ohp, 'Repetições')) === '["10","9","8","8"]', 'a new set copies the one before it')
await ohp.getByRole('button', { name: `Remover série 4 de ${OHP}` }).click()
const sessionMuscles = session.locator('.session-muscles')
assert(await sessionMuscles.count() === 0, 'with only Supino sets done, which have no muscle group, the card names no muscles')
await ohp.getByRole('button', { name: `Série 1 de ${OHP} feita` }).click()
assert(await sessionMuscles.textContent() === 'Músculos: Ombros 1', `ticking a set of ${OHP} names Ombros with 1 set (got ${await sessionMuscles.textContent()})`)
for (const i of [2, 3]) await ohp.getByRole('button', { name: `Série ${i} de ${OHP} feita` }).click()
assert(await sessionMuscles.textContent() === 'Músculos: Ombros 3', 'and counts each done set')
assert(await session.locator('.sets-done').textContent() === '5/5 séries feitas', 'the card counts the sets done')
await ohp.getByRole('button', { name: OHP }).click()
assert(JSON.stringify(await ticks(ohp)) === '["true","true","true"]', 'tapping a collapsed exercise reopens it')
await session.getByLabel('Notas do treino').fill('Ombro bem')
assert(await region('Treinos anteriores').count() === 0, 'with no session in the three days before, there is no Treinos anteriores card')
const endFeel = session.getByRole('group', { name: 'No fim do treino' })
await endFeel.getByRole('button', { name: 'No fim do treino: Bem' }).click()
await supino.getByRole('button', { name: 'Supino' }).click()
const supinoNoteToggle = supino.getByRole('button', { name: 'Nota de Supino' })
assert(await supinoNoteToggle.getAttribute('aria-expanded') === 'false', 'an exercise note starts closed')
await supinoNoteToggle.click()
const supinoNote = supino.getByRole('textbox', { name: 'Nota de Supino' })
assert(await supinoNote.getAttribute('placeholder') === 'Dores, desconforto, como correu', 'the exercise note asks about pain and discomfort')
assert(await supino.getByRole('button', { name: 'Ditar nota' }).count() === 1, 'an exercise note has a mic button')
await supinoNote.fill('Ombro esq. a picar na 2.ª série')
const liftTimes = await supino.locator('.note-times').textContent()
assert(/^Escrito a \d+ [a-z]{3}, \d\d:\d\d$/.test(liftTimes), `the exercise note shows when it was written (got ${liftTimes})`)
await page.screenshot({ path: `${S}/workout-session-done-desktop.png`, fullPage: true })
await session.screenshot({ path: `${S}/workout-session-muscles.png` })

await reloadApp(page)
await supino.getByRole('button', { name: 'Supino' }).click()
await ohp.getByRole('button', { name: OHP }).click()
assert(JSON.stringify(await values(supino, 'Repetições')) === '["8","7"]' && JSON.stringify(await values(supino, 'Kg')) === '["60","61,25"]', 'Supino sets persisted across reload')
assert(JSON.stringify(await values(ohp, 'Kg')) === '["","",""]', `${OHP} stays bodyweight, with no kg`)
assert(await session.getByLabel('Notas do treino').inputValue() === 'Ombro bem', 'notes persisted')
assert(await endFeel.getByRole('button', { pressed: true }).textContent() === 'Bem', 'the end feel persisted across reload')
assert(await supinoNote.inputValue() === 'Ombro esq. a picar na 2.ª série', 'the exercise note persisted and opens by itself')
const stored = await readStored(page)
assert(stored.workoutSessions.version === 4 && stored.workoutSessions.sessions.length === 1, 'one session stored under its own key, version 4')
assert(stored.workoutSessions.sessions[0].feel === 4 && !('after' in stored.workoutSessions.sessions[0]), 'the end feel is stored as 4, and no After-effects key yet')
const supinoSets = stored.workoutSessions.sessions[0].exercises.find((e) => e.note).sets
assert(JSON.stringify(supinoSets.map((s) => [s.done, s.kg, s.reps, s.rir])) === '[[true,60,8,null],[true,61.25,7,null]]', `stored sets are done, with kg in decimals (got ${JSON.stringify(supinoSets)})`)
assert(stored.workoutPlans.version === 4 && stored.workoutPlans.plans[0].split === 'ppf', 'the plan is stored as version 4 with its split')
assert(stored.exercises.exercises.some((e) => e.name === 'Supino') && stored.exercises.exercises.some((e) => e.name === BENCH), 'the user’s and the catalog’s exercises are stored by name')

await page.goto(`${URL}#treino/${yesterday}`)
await region('Push').waitFor()

await page.getByRole('button', { name: 'Dia seguinte' }).click()
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(0)) }).waitFor()
assert(await page.getByRole('button', { name: 'Dia seguinte' }).isDisabled(), 'today is the last day that can be logged')
const recent = region('Treinos anteriores').getByRole('group', { name: 'Push, ontem' })
assert(await recent.locator('.recent-meta').textContent() === 'ontem · no fim: Bem', `the day after, Treinos anteriores lists yesterday's session with its end feel (got ${await recent.locator('.recent-meta').textContent()})`)
await recent.getByRole('textbox', { name: 'Como está o corpo' }).fill('Peito dorido')
await recent.getByRole('button', { name: 'Nota de Supino' }).click()
await recent.getByRole('textbox', { name: 'Nota de Supino' }).fill('Ombro esq. dói ao levantar o braço')
await reloadApp(page)
assert(await recent.getByRole('textbox', { name: 'Como está o corpo' }).inputValue() === 'Peito dorido', 'the session note of the day after persisted across reload')
assert(await recent.getByRole('textbox', { name: 'Nota de Supino' }).inputValue() === 'Ombro esq. dói ao levantar o braço', 'and the Supino one, open by itself')
const after = (await readStored(page)).workoutSessions.sessions[0].after.map((a) => [a.date, a.exerciseId === null ? null : 'supino', a.note.text])
assert(JSON.stringify(after) === JSON.stringify([[toIsoDate(daysAgo(0)), null, 'Peito dorido'], [toIsoDate(daysAgo(0)), 'supino', 'Ombro esq. dói ao levantar o braço']]), `two After-effects stored on yesterday's session, dated today (got ${JSON.stringify(after)})`)
await page.getByRole('button', { name: 'Dia anterior' }).click()
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(1)) }).waitFor()
const afterList = region('Push').getByRole('group', { name: 'Depois do treino' })
const items = await afterList.locator('.after-item').evaluateAll((lis) => lis.map((li) => [...li.children].slice(0, 2).map((c) => c.textContent).join(' / ')))
assert(JSON.stringify(items) === JSON.stringify(['Dia seguinteTreino / Peito dorido', 'Dia seguinteSupino / Ombro esq. dói ao levantar o braço']), `the original session card shows them read only (got ${JSON.stringify(items)})`)
await page.getByRole('button', { name: 'Dia seguinte' }).click()
await page.locator('.date-stepper h2', { hasText: longDate.format(daysAgo(0)) }).waitFor()
assert((await starts()).join('|') === 'Começar Pull|Push|Full body|Treino livre', `after Push, Registo leads with Pull (got ${(await starts()).join('|')})`)
await page.getByRole('button', { name: 'Push', exact: true }).click()
assert(JSON.stringify(await values(supino, 'Kg')) === '["61,25","61,25","61,25","61,25"]' && JSON.stringify(await values(supino, 'Repetições')) === '["8","8","8","8"]', 'a second session suggests Supino at the last set’s load, one rep more')
assert((await supino.locator('.lift-note').textContent()).endsWith('Última: 61,25 kg × 7 · alvo 2. Faz 8 com 61,25 kg.'), `and says why (got ${await supino.locator('.lift-note').textContent()})`)
assert(JSON.stringify(await ticks(supino)) === '["false","false","false","false"]', 'suggested sets start pending')
assert(JSON.stringify(await values(ohp, 'Repetições')) === '["9","9","9"]' && JSON.stringify(await values(ohp, 'Kg')) === '["","",""]', `a bodyweight exercise moves only its reps (got ${JSON.stringify(await values(ohp, 'Repetições'))})`)
assert((await ohp.locator('.lift-note').textContent()).endsWith('Última: peso corporal × 10/9/8 · alvo 2. Faz 9 com peso corporal.'), `the hardest set, 8 with no RIR, decides and names only the target (got ${await ohp.locator('.lift-note').textContent()})`)
await supino.getByRole('button', { name: 'Série 1 de Supino feita' }).click()
assert(JSON.stringify(await ticks(supino)) === '["true","false","false","false"]', 'one tap marks a suggested set done as shown')
await addExercise(session, 'Prancha')
assert(JSON.stringify(await values(session.getByRole('group', { name: 'Prancha' }), 'Repetições')) === '[""]', 'a new exercise starts with one empty set')
await page.screenshot({ path: `${S}/workout-session-desktop.png`, fullPage: true })

await page.setViewportSize({ width: 390, height: 844 })
assert(await noScroll(), 'Treino Registo has no horizontal scroll at 390 px')
const tick = await supino.getByRole('button', { name: 'Série 2 de Supino feita' }).boundingBox()
assert(tick.width >= 44 && tick.height >= 44, 'the ✓ is thumb-sized')
await page.screenshot({ path: `${S}/workout-session-mobile.png`, fullPage: true })
await tab('Plano de treino').click()
await region('Push').waitFor()
assert(await noScroll(), 'Plano de treino has no horizontal scroll at 390 px')
await page.setViewportSize({ width: 375, height: 812 })
assert(await noScroll(), 'Plano de treino with Músculos por semana has no horizontal scroll at 375 px')
await region('Músculos por semana').screenshot({ path: `${S}/workout-muscles-mobile.png` })
await page.setViewportSize({ width: 390, height: 844 })
await page.screenshot({ path: `${S}/workout-plan-mobile.png`, fullPage: true })

assert(errors.length === 0, 'no console errors: ' + errors.join(' / '))
await browser.close()
